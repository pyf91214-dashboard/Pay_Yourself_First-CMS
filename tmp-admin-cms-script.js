            normalizeTaxSections(sections, source = {}) {
                const defaults = this.getDefaultTaxSections(source);
                if (!Array.isArray(sections)) return defaults;

                return sections
                    .map((section, index) => {
                        const type = section?.type || section?.id;
                        const fallback = defaults.find(item => item.type === type || item.id === type);
                        if (!fallback) return null;

                        const normalized = {
                            ...fallback,
                            ...section,
                            id: section?.id || `${fallback.id}-${index + 1}`,
                            type: fallback.type,
                            label: section?.label || fallback.label
                        };

                        if (normalized.type === 'hero') {
                            normalized.buttons = (Array.isArray(section?.buttons) ? section.buttons : fallback.buttons).map(button => this.createTaxButton(button));
                        }

                        if (normalized.type === 'includes') {
                            normalized.items = (Array.isArray(section?.items) ? section.items : fallback.items).map((item, itemIndex) => this.createTaxIncludeItem(item, itemIndex));
                        }

                        if (normalized.type === 'pricing_summary') {
                            normalized.rows = (Array.isArray(section?.rows) ? section.rows : fallback.rows).map(row => this.createTaxPricingRow(row));
                        }

                        if (normalized.type === 'done_for_you' || normalized.type === 'value_cta' || normalized.type === 'affiliate_cta' || normalized.type === 'bottom_cta') {
                            if (normalized.button || fallback.button) {
                                normalized.button = this.createTaxButton(section?.button || fallback.button);
                            }
                        }

                        if (normalized.type === 'done_for_you' || normalized.type === 'features' || normalized.type === 'affiliate_cta') {
                            normalized.list = Array.isArray(section?.list) ? section.list : fallback.list;
                        }

                        if (normalized.type === 'savings_table') {
                            normalized.rows = (Array.isArray(section?.rows) ? section.rows : fallback.rows).map(row => this.createTaxSavingsRow(row));
                        }

                        if (normalized.type === 'timeline') {
                            normalized.cards = (Array.isArray(section?.cards) ? section.cards : fallback.cards).map((card, cardIndex) => this.createTaxTimelineCard(card, cardIndex));
                        }

                        if (normalized.type === 'faq') {
                            normalized.questions = (Array.isArray(section?.questions) ? section.questions : fallback.questions).map(item => this.createTaxFaqItem(item));
                        }

                        if (normalized.type === 'bottom_cta') {
                            normalized.features = (Array.isArray(section?.features) ? section.features : fallback.features).map((item, itemIndex) => this.createTaxFeatureBadge(item, itemIndex));
                        }

                        return normalized;
                    })
                    .filter(Boolean);
            },

